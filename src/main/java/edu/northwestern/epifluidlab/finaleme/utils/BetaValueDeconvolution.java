    public void doMain(String[] args) throws Exception {
        CmdLineParser parser = new CmdLineParser(this);
        try {
            parser.parseArgument(args);
        } catch (CmdLineException e) {
            System.err.println(e.getMessage());
            System.err.println(USAGE);
            parser.printUsage(System.err);
            return;
        }
        if (help) {
            System.err.println(USAGE);
            parser.printUsage(System.err);
            return;
        }
        if (queryFiles.isEmpty()) {
            System.err.println("Error: no query sample files provided.");
            System.err.println(USAGE);
            return;
        }

        // Validate top-level mode.
        boolean useRefPanel = (refPanelFile != null);
        boolean haveRefBetasAndGroups = (refBetasArg != null && refGroupsFile != null);
        boolean haveOneOfRefInputs = (refBetasArg != null || refGroupsFile != null);
        if (haveOneOfRefInputs && !haveRefBetasAndGroups) {
            System.err.println("Error: provide both -refBetas and -refGroups together.");
            System.err.println(USAGE);
            return;
        }

        // Validate mode: either -markerRegions or -cgiShoreRegions
        // (unless -refPanel is used, which already carries the marker coordinates)
        if (markerRegionsFile == null && cgiShoreBed == null && !useRefPanel) {
            System.err.println("Error: provide either -markerRegions, -cgiShoreRegions, or -refPanel.");
            System.err.println(USAGE);
            return;
        }

        // CpG index is always needed for parsing query .beta / .prediction.bed
        // files. When -refPanel is used, -cpgIndex is still required for queries.
        if (cpgIndexFile == null) {
            System.err.println("Error: -cpgIndex is required for parsing query samples.");
            System.err.println(USAGE);
            return;
        }
        log.info("Loading CpG index...");
        CpgIndex cpgIndex = loadCpgIndex(cpgIndexFile);

        List<Window> selectedWindows;
        double[][] refSelected;
        List<String> cellTypes;

        if (useRefPanel) {
            // ===== Reference panel mode: load pre-aggregated panel directly =====
            log.info("Loading pre-aggregated reference panel: {}", refPanelFile);
            Object[] panelData = loadReferencePanel(refPanelFile, cpgIndex);
            selectedWindows = (List<Window>) panelData[0];
            double[][] refMatrix = (double[][]) panelData[1];
            cellTypes = (List<String>) panelData[2];
            this.markerTargets = (List<String>) panelData[3];
            log.info("Reference panel: {} markers x {} cell types", selectedWindows.size(), cellTypes.size());

            // Binarize reference
            refSelected = new double[selectedWindows.size()][cellTypes.size()];
            for (int i = 0; i < selectedWindows.size(); i++) {
                for (int j = 0; j < cellTypes.size(); j++) {
                    double v = refMatrix[i][j];
                    refSelected[i][j] = Double.isNaN(v) || v < binarizeThreshold ? 0.0 : 1.0;
                }
            }

        } else {
            if (markerRegionsFile != null) {
                // ===== Marker regions mode =====
                double[][] refMatrix;
                if (haveRefBetasAndGroups) {
                    // Legacy behavior: compute reference from .beta files.
                    List<String> refBetaPaths = parseRefBetas(refBetasArg);
                    Map<String, String> sampleToGroup = loadGroupsFile(refGroupsFile);
                    log.info("Loaded {} reference beta files, {} groups",
                            refBetaPaths.size(), new HashSet<>(sampleToGroup.values()).size());
                    cellTypes = new ArrayList<>(new TreeSet<>(sampleToGroup.values()));

                    log.info("Marker regions mode: loading regions from {}", markerRegionsFile);
                    selectedWindows = loadMarkerRegions(markerRegionsFile);
                    log.info("Loaded {} marker regions", selectedWindows.size());

                    log.info("Computing reference methylation at marker regions (mode: {})...", replicateMode);
                    refMatrix = loadReferenceMethylation(
                            refBetaPaths, sampleToGroup, cellTypes, selectedWindows, cpgIndex);
                } else {
                    // New behavior: if marker atlas has embedded values, use directly.
                    log.info("Marker regions mode: trying embedded reference values from {}", markerRegionsFile);
                    Object[] panelData = loadReferencePanel(markerRegionsFile, cpgIndex);
                    selectedWindows = (List<Window>) panelData[0];
                    refMatrix = (double[][]) panelData[1];
                    cellTypes = (List<String>) panelData[2];
                    this.markerTargets = (List<String>) panelData[3];
                    if (cellTypes == null || cellTypes.isEmpty()) {
                        System.err.println("Error: -markerRegions file has no embedded cell-type value columns. "
                                + "Provide -refBetas/-refGroups or a marker atlas with per-cell-type values.");
                        System.err.println(USAGE);
                        return;
                    }
                    log.info("Embedded marker atlas reference: {} markers x {} cell types",
                            selectedWindows.size(), cellTypes.size());
                }

                // Binarize reference
                refSelected = new double[selectedWindows.size()][cellTypes.size()];
                for (int i = 0; i < selectedWindows.size(); i++) {
                    for (int j = 0; j < cellTypes.size(); j++) {
                        double v = refMatrix[i][j];
                        refSelected[i][j] = Double.isNaN(v) || v < binarizeThreshold ? 0.0 : 1.0;
                    }
                }

            } else {
                // ===== Original mode: tile CGI+shore, filter by variability =====
                if (!haveRefBetasAndGroups) {
                    System.err.println("Error: -cgiShoreRegions mode requires -refBetas and -refGroups.");
                    System.err.println(USAGE);
                    return;
                }
                List<String> refBetaPaths = parseRefBetas(refBetasArg);
                Map<String, String> sampleToGroup = loadGroupsFile(refGroupsFile);
                log.info("Loaded {} reference beta files, {} groups",
                        refBetaPaths.size(), new HashSet<>(sampleToGroup.values()).size());
                cellTypes = new ArrayList<>(new TreeSet<>(sampleToGroup.values()));

                log.info("Generating {}bp windows within CGI+shore regions...", windowSize);
                List<Window> windows = generateWindows(cgiShoreBed, cpgIndex);
                log.info("Generated {} windows", windows.size());

                log.info("Loading reference methylation data (mode: {})...", replicateMode);
                double[][] refMatrix = loadReferenceMethylation(
                        refBetaPaths, sampleToGroup, cellTypes, windows, cpgIndex);

                log.info("Filtering windows (minCoverage={}, topVariable={}%)...",
                        minCoverage, topVariablePercent * 100);
                int[] selectedIndices = filterAndSelectWindows(refMatrix, cellTypes.size());
                log.info("Selected {} windows after filtering", selectedIndices.length);

                if (selectedIndices.length == 0) {
                    log.error("No windows passed filtering. Try lowering -minCoverage or -topVariablePercent.");
                    return;
                }

                refSelected = new double[selectedIndices.length][cellTypes.size()];
                selectedWindows = new ArrayList<>();
                for (int i = 0; i < selectedIndices.length; i++) {
                    selectedWindows.add(windows.get(selectedIndices[i]));
                    for (int j = 0; j < cellTypes.size(); j++) {
                        double v = refMatrix[selectedIndices[i]][j];
                        refSelected[i][j] = v < binarizeThreshold ? 0.0 : 1.0;
                    }
                }
            }
        }

        // Step 6 & 7: Process each query sample
        List<String> sampleNames = new ArrayList<>();
        List<double[]> allWeights = new ArrayList<>();
        List<BootstrapResult> allBoot = new ArrayList<>();  // one per sample when bootstrap enabled
        List<PermutationResult> allPerm = new ArrayList<>();  // one per sample when permutation enabled

        for (String queryFile : queryFiles) {
            log.info("Processing query: {}", queryFile);
            double[] queryValues = loadQuerySample(queryFile, selectedWindows, cpgIndex);

            // Binarize query
            for (int i = 0; i < queryValues.length; i++) {
                if (Double.isNaN(queryValues[i])) {
                    queryValues[i] = 0.0; // treat missing as unmethylated
                } else {
                    queryValues[i] = queryValues[i] < binarizeThreshold ? 0.0 : 1.0;
                }
            }

            double[] weights;
            if ("NNLS".equalsIgnoreCase(solver)) {
                weights = solveNNLS(refSelected, queryValues);
            } else {
                weights = solveQP(refSelected, queryValues);
            }

            sampleNames.add(new File(queryFile).getName());
            allWeights.add(weights);

            if (bootstrap) {
                log.info("Running bootstrap ({} replicates, {} threads, stratified={})...",
                        nBootstrap, bootstrapThreads, bootstrapStratified);
                BootstrapResult br = runBootstrap(refSelected, queryValues, weights);
                allBoot.add(br);
            }
            if (permutationTest) {
                log.info("Running column-permutation test ({} permutations per cell type, {} threads)...",
                        nPermutations, bootstrapThreads);
                PermutationResult pr = runPermutationTest(refSelected, queryValues, weights);
                allPerm.add(pr);
            }
        }

        // Step 8: Output — two schemas, chosen by whether bootstrap was run.
        PrintWriter out = outputFile != null ? new PrintWriter(new FileWriter(outputFile)) : new PrintWriter(System.out);

        if (bootstrap || permutationTest) {
            // Long-form output: one row per (sample, cell_type) with stats.
            //
            // When both -bootstrap and -permutationTest are on:
            //   - CI comes from bootstrap
            //   - p-value / q-value / significant come from permutation
            //     (permutation p has better resolution at small values)
            // When only one is on, that source supplies all three.
            double alpha = 1.0 - ciLevel;
            double loPct = 100.0 * (alpha / 2.0);
            double hiPct = 100.0 * (1.0 - alpha / 2.0);
            String pSource = permutationTest ? "permutation" : "bootstrap";
            out.println("sample\tcell_type\tproportion\tCI_lower\tCI_upper\tp_value\tq_value\tsignificant\tp_source\tn_replicates");
            for (int s = 0; s < sampleNames.size(); s++) {
                String sname = sampleNames.get(s);
                double[] w = allWeights.get(s);
                BootstrapResult br = bootstrap ? allBoot.get(s) : null;
                PermutationResult pr = permutationTest ? allPerm.get(s) : null;
                for (int c = 0; c < cellTypes.size(); c++) {
                    double prop = w[c] < 0.001 ? 0.0 : w[c];
                    double ciLo = (br != null) ? br.ciLower[c] : Double.NaN;
                    double ciHi = (br != null) ? br.ciUpper[c] : Double.NaN;
                    double p = (pr != null) ? pr.pValue[c] : br.pValue[c];
                    double q = (pr != null) ? pr.qValue[c] : br.qValue[c];
                    String sig = (q <= fdrAlpha) ? "YES" : "NO";
                    int nRep = (pr != null) ? pr.nPermutations : nBootstrap;
                    if (Double.isNaN(ciLo)) {
                        out.printf(
                                "%s\t%s\t%.4f\tNA\tNA\t%.4g\t%.4g\t%s\t%s\t%d%n",
                                sname, cellTypes.get(c), prop,
                                p, q, sig, pSource, nRep);
                    } else {
                        out.printf(
                                "%s\t%s\t%.4f\t%.4f\t%.4f\t%.4g\t%.4g\t%s\t%s\t%d%n",
                                sname, cellTypes.get(c), prop,
                                ciLo, ciHi,
                                p, q, sig, pSource, nRep);
                    }
                }
            }
            log.info("Stats output: CI {} at [{}%, {}%], p-values from {}, FDR threshold {}",
                    bootstrap ? "from bootstrap" : "(not computed)", loPct, hiPct, pSource, fdrAlpha);
        } else {
            // Wide-form output (legacy): cell_type | sample1 | sample2 | ...
            out.print("cell_type");
            for (String name : sampleNames) {
                out.print("\t" + name);
            }
            out.println();
            for (int c = 0; c < cellTypes.size(); c++) {
                out.print(cellTypes.get(c));
                for (double[] weights : allWeights) {
                    double w = weights[c];
                    out.printf("\t%.4f", w < 0.001 ? 0.0 : w);
                }
                out.println();
            }
        }

        out.flush();
        if (outputFile != null) out.close();
        log.info("Done.");
    }

    // ========================= CpG Index Loading =========================

    private CpgIndex loadCpgIndex(String path) throws IOException {
        LinkedHashMap<String, ArrayList<Integer>> chrToPositions = new LinkedHashMap<>();
        InputStream input = path.endsWith(".gz")
                ? new GZIPInputStream(new FileInputStream(path))
                : new FileInputStream(path);
        try (BufferedReader br = new BufferedReader(new InputStreamReader(input, StandardCharsets.UTF_8))) {
            String line;
            while ((line = br.readLine()) != null) {
                if (line.isEmpty() || line.startsWith("#")) continue;
                String[] parts = line.split("\t");
                if (parts.length < 2) continue;
                String chr = parts[0];
                int start;
                try {
                    start = Integer.parseInt(parts[1]);
                } catch (NumberFormatException e) {
                    continue;
                }
                chrToPositions.computeIfAbsent(chr, k -> new ArrayList<>()).add(start);
            }
        }

        LinkedHashMap<String, int[]> chrPositions = new LinkedHashMap<>();
        HashMap<String, Integer> chrOffsets = new HashMap<>();
        int totalSites = 0;
        for (Map.Entry<String, ArrayList<Integer>> entry : chrToPositions.entrySet()) {
            ArrayList<Integer> positions = entry.getValue();
            Collections.sort(positions);
            // Deduplicate
            int[] posArray = positions.stream().mapToInt(Integer::intValue).distinct().toArray();
            chrOffsets.put(entry.getKey(), totalSites);
            chrPositions.put(entry.getKey(), posArray);
            totalSites += posArray.length;
        }
        log.info("CpG index: {} sites across {} chromosomes", totalSites, chrPositions.size());
        return new CpgIndex(chrPositions, chrOffsets, totalSites);
    }

    // ========================= Marker Regions Loading =========================

    /**
     * Load pre-defined marker regions from an atlas TSV or BED file.
     * Extracts only the genomic coordinates (chr, start, end, startCpG, endCpG).
     *
     * Supports two formats:
     *   - Atlas TSV: chr start end startCpG endCpG target name direction [cell type cols...]
     *   - BED file:  chr start end startCpG endCpG [optional extra cols]
     *
     * Auto-detects format by checking if column 1 is numeric (BED) or has a header.
     */

    /**
     * Load a pre-aggregated reference panel TSV.
     *
     * Format (generated by generate_cgi_shore_markers.py stage 4):
     *   chrom  start  end  CellType1       CellType2       ...
     *   chr1   1000   1500 125/250         30/250          ...
     *
     * Each cell value is either "methylated_count/total_count" (detected by
     * the presence of "/") or a plain float beta value (0.85). Both formats
     * are handled transparently.
     *
     * Returns Object[] { List<Window>, double[][], List<String> }:
     *   [0] windows — marker regions as Window objects
     *   [1] refMatrix — (nMarkers x nCellTypes) methylation matrix
     *   [2] cellTypes — ordered list of cell type names from the header
     */
    private int findHeaderColumnIndex(String[] header, String... names) {
        Set<String> target = new HashSet<>();
        for (String n : names) {
            target.add(n.toLowerCase(Locale.ROOT));
        }
        for (int i = 0; i < header.length; i++) {
            String h = header[i].trim().toLowerCase(Locale.ROOT);
            if (h.startsWith("#")) h = h.substring(1);
            if (target.contains(h)) return i;
        }
        return -1;
    }

    private Object[] loadReferencePanel(String path, CpgIndex cpgIndex) throws IOException {
        BufferedReader br;
        if (path.endsWith(".gz")) {
            br = new BufferedReader(new InputStreamReader(
                    new GZIPInputStream(new FileInputStream(path)), StandardCharsets.UTF_8));
        } else {
            br = new BufferedReader(new FileReader(path));
        }

        List<Window> windows = new ArrayList<>();
        List<double[]> rows = new ArrayList<>();
        List<String> cellTypes = null;
        Set<String> seen = new HashSet<>();
        int skippedNonAutosome = 0;
        int skippedDuplicate = 0;
        int skippedNoCpg = 0;
        int parsedRows = 0;
        int coordParseErrors = 0;

        int chrCol = 0;
        int startCol = 1;
        int endCol = 2;
        int startCpgCol = -1;
        int endCpgCol = -1;
        int firstValueCol = 3;
        int targetCol = -1;
        List<String> markerTargets = new ArrayList<>();

        try {
            String line;
            boolean first = true;
            while ((line = br.readLine()) != null) {
                line = line.trim();
                if (line.isEmpty() || line.startsWith("#")) continue;

                String[] parts = line.split("\t");

                if (first) {
                    // Header row: either panel-style (chrom/start/end/...) or
                    // atlas-style (chr/start/end/startCpG/endCpG/target/name/direction/...).
                    first = false;
                    // Check if first column is numeric (headerless BED) or a label
                    try {
                        Integer.parseInt(parts[1]);
                        // Looks numeric → no header, parse as data
                    } catch (NumberFormatException e) {
                        // Header present: detect coordinate and value columns.
                        int tmpChr = findHeaderColumnIndex(parts, "chrom", "chr", "#chr");
                        int tmpStart = findHeaderColumnIndex(parts, "start");
                        int tmpEnd = findHeaderColumnIndex(parts, "end");
                        if (tmpChr >= 0 && tmpStart >= 0 && tmpEnd >= 0) {
                            chrCol = tmpChr;
                            startCol = tmpStart;
                            endCol = tmpEnd;
                        }

                        startCpgCol = findHeaderColumnIndex(parts, "startcpg", "start_cpg");
                        endCpgCol = findHeaderColumnIndex(parts, "endcpg", "end_cpg");
                        // `target` column carries the primary cell-type label per marker
                        // (used by stratified bootstrap to resample within cell types).
                        targetCol = findHeaderColumnIndex(parts, "target");
                        int directionCol = findHeaderColumnIndex(parts, "direction");
                        if (directionCol >= 0 && directionCol + 1 < parts.length) {
                            firstValueCol = directionCol + 1;
                        } else {
                            firstValueCol = Math.max(Math.max(chrCol, startCol), endCol) + 1;
                        }

                        // Extract cell-type names from the value columns.
                        cellTypes = new ArrayList<>();
                        for (int i = firstValueCol; i < parts.length; i++) {
                            cellTypes.add(parts[i]);
                        }
                        continue;
                    }
                }

                if (parts.length <= Math.max(endCol, firstValueCol)) continue;

                String chr;
                int start;
                int end;
                try {
                    chr = parts[chrCol];
                    start = Integer.parseInt(parts[startCol]);
                    end = Integer.parseInt(parts[endCol]);
                } catch (Exception ex) {
                    coordParseErrors++;
                    continue;
                }
                parsedRows++;

                // Keep refPanel behavior consistent with -markerRegions mode:
                // skip non-autosome chromosomes and deduplicate by coordinates.
                if (chr.contains("_") || chr.equals("chrX") || chr.equals("chrY") || chr.equals("chrM")) {
                    skippedNonAutosome++;
                    continue;
                }
                String key = chr + ":" + start + "-" + end;
                if (!seen.add(key)) {
                    skippedDuplicate++;
                    continue;
                }

                int startCpgIdx = -1;
                int endCpgExclusive = 0;
                // If atlas carries startCpG/endCpG, use them directly to keep
                // marker-based behavior consistent.
                if (startCpgCol >= 0 && endCpgCol >= 0
                        && startCpgCol < parts.length && endCpgCol < parts.length) {
                    try {
                        int s = Integer.parseInt(parts[startCpgCol]);
                        int e = Integer.parseInt(parts[endCpgCol]);
                        if (s > 0 && e >= s) {
                            startCpgIdx = s;
                            endCpgExclusive = e;
                        }
                    } catch (NumberFormatException ignored) {
                        // fall through to coordinate-derived CpG indices
                    }
                }

                // Otherwise derive CpG indices from coordinates.
                if (endCpgExclusive == 0) {
                    int endCpgLast = cpgIndex.getLastCpgIndexBefore(chr, end);
                    int s = cpgIndex.getFirstCpgIndexAtOrAfter(chr, start);
                    if (s > 0 && endCpgLast >= s) {
                        startCpgIdx = s;
                        endCpgExclusive = endCpgLast + 1;
                    }
                }

                if (endCpgExclusive == 0) {
                    skippedNoCpg++;
                    continue;
                }
                windows.add(new Window(chr, start, end, startCpgIdx, endCpgExclusive));

                // Capture the `target` cell-type label for this marker row (or null if absent).
                String targetLabel = null;
                if (targetCol >= 0 && targetCol < parts.length) {
                    targetLabel = parts[targetCol].trim();
                    if (targetLabel.isEmpty()) targetLabel = null;
                }
                markerTargets.add(targetLabel);

                int nCt = (cellTypes != null) ? cellTypes.size() : Math.max(0, parts.length - firstValueCol);
                double[] vals = new double[nCt];
                Arrays.fill(vals, Double.NaN);
                for (int i = 0; i < nCt; i++) {
                    int col = firstValueCol + i;
                    if (col >= parts.length) break;
                    String cell = parts[col].trim();
                    if (cell.contains("/")) {
                        // Count ratio format: "125/250"
                        String[] kn = cell.split("/", 2);
                        try {
                            long k = Long.parseLong(kn[0]);
                            long n = Long.parseLong(kn[1]);
                            // Keep refPanel mode consistent with
                            // loadReferenceMethylation(): enforce minCoverage.
                            vals[i] = (n >= minCoverage) ? (double) k / n : Double.NaN;
                        } catch (NumberFormatException e) {
                            vals[i] = Double.NaN;
                        }
                    } else {
                        // Plain float format: "0.85"
                        try {
                            vals[i] = Double.parseDouble(cell);
                        } catch (NumberFormatException e) {
                            vals[i] = Double.NaN;
                        }
                    }
                }
                rows.add(vals);
            }
        } finally {
            br.close();
        }

        if (cellTypes == null && !rows.isEmpty()) {
            // No header detected — generate placeholder cell type names
            cellTypes = new ArrayList<>();
            for (int i = 0; i < rows.get(0).length; i++) {
                cellTypes.add("CellType" + (i + 1));
            }
        }

        int nMarkers = rows.size();
        int nCt = cellTypes != null ? cellTypes.size() : 0;
        double[][] refMatrix = new double[nMarkers][nCt];
        for (int i = 0; i < nMarkers; i++) {
            double[] row = rows.get(i);
            for (int j = 0; j < Math.min(row.length, nCt); j++) {
                refMatrix[i][j] = row[j];
            }
        }

        log.info(
                "Reference panel parsing: {} data rows -> {} kept "
                        + "(skipped {} non-autosome, {} duplicate, {} no-CpG, {} coord-parse)",
                parsedRows, nMarkers, skippedNonAutosome, skippedDuplicate, skippedNoCpg, coordParseErrors
        );
        if (targetCol >= 0) {
            long withTarget = markerTargets.stream().filter(Objects::nonNull).count();
            long distinct = markerTargets.stream().filter(Objects::nonNull).distinct().count();
            log.info("Reference panel `target` column: {} markers labeled, {} distinct cell types",
                    withTarget, distinct);
        } else {
            log.info("Reference panel has no `target` column — stratified bootstrap will "
                    + "fall back to uniform if requested.");
        }

        return new Object[]{windows, refMatrix, cellTypes, markerTargets};
    }

    private List<Window> loadMarkerRegions(String path) throws IOException {
        List<Window> windows = new ArrayList<>();

        BufferedReader br;
        if (path.endsWith(".gz")) {
            br = new BufferedReader(new InputStreamReader(
                    new GZIPInputStream(new FileInputStream(path)), StandardCharsets.UTF_8));
        } else {
            br = new BufferedReader(new FileReader(path));
        }

        try {
            String line;
            while ((line = br.readLine()) != null) {
                if (line.isEmpty() || line.startsWith("#")) continue;
                String[] parts = line.split("\t");
                if (parts.length < 5) continue;

                // Skip header row (if column 1 is not numeric)
                try {
                    Integer.parseInt(parts[1]);
                } catch (NumberFormatException e) {
                    continue; // header row
                }

                String chr = parts[0];
                int start, end, startCpG, endCpG;
                try {
                    start = Integer.parseInt(parts[1]);
                    end = Integer.parseInt(parts[2]);
                    startCpG = Integer.parseInt(parts[3]);
                    endCpG = Integer.parseInt(parts[4]);
                } catch (NumberFormatException e) {
                    continue;
                }

                // Skip non-autosome
                if (chr.contains("_") || chr.equals("chrX") || chr.equals("chrY") || chr.equals("chrM")) {
                    continue;
                }

                windows.add(new Window(chr, start, end, startCpG, endCpG));
            }
        } finally {
            br.close();
        }

        // Deduplicate by coordinates
        Set<String> seen = new HashSet<>();
        List<Window> unique = new ArrayList<>();
        for (Window w : windows) {
            String key = w.chr + ":" + w.start + "-" + w.end;
            if (seen.add(key)) {
                unique.add(w);
            }
        }

        log.info("Loaded {} unique marker regions from {}", unique.size(), path);
        return unique;
    }

    // ========================= Window Generation =========================

    private List<Window> generateWindows(String bedPath, CpgIndex cpgIndex) throws IOException {
        List<Window> windows = new ArrayList<>();
        try (BufferedReader br = new BufferedReader(new FileReader(bedPath))) {
            String line;
            while ((line = br.readLine()) != null) {
                if (line.isEmpty() || line.startsWith("#")) continue;
                String[] parts = line.split("\t");
                String chr = parts[0];
                int regionStart = Integer.parseInt(parts[1]);
                int regionEnd = Integer.parseInt(parts[2]);

                // Skip non-autosome chromosomes
                if (chr.contains("_") || chr.equals("chrX") || chr.equals("chrY") || chr.equals("chrM")) {
                    continue;
                }

                // Tile into non-overlapping windows
                for (int wStart = regionStart; wStart + windowSize <= regionEnd; wStart += windowSize) {
                    int wEnd = wStart + windowSize;
                    int startIdx = cpgIndex.getFirstCpgIndexAtOrAfter(chr, wStart);
                    int endIdx = cpgIndex.getLastCpgIndexBefore(chr, wEnd);
                    if (startIdx > 0 && endIdx > 0 && endIdx >= startIdx) {
                        windows.add(new Window(chr, wStart, wEnd, startIdx, endIdx + 1));
                    }
                }
            }
        }
        return windows;
    }

