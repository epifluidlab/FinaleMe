    // ========================= Bootstrap / CI / p-value / q-value =========================

    /**
     * Per-sample bootstrap output: proportion CI, p-value, and BH q-value per cell type.
     * p_value for cell type c is Pr(w_c <= epsilon | bootstrap), i.e. the bootstrap
     * tail probability against H0: w_c = 0. Small p -> the fraction was reliably
     * non-zero across replicates -> more trust in the cell-type contribution.
     * q_value is the Benjamini-Hochberg FDR-adjusted p-value across cell types.
     */
    static class BootstrapResult {
        final double[] ciLower;  // length K
        final double[] ciUpper;  // length K
        final double[] pValue;   // length K
        final double[] qValue;   // length K
        final double[][] replicates; // (B, K) — kept for optional inspection

        BootstrapResult(double[] ciLower, double[] ciUpper, double[] pValue, double[] qValue, double[][] replicates) {
            this.ciLower = ciLower;
            this.ciUpper = ciUpper;
            this.pValue = pValue;
            this.qValue = qValue;
            this.replicates = replicates;
        }
    }

    /**
     * Run B bootstrap replicates by resampling marker rows of the NNLS system
     * with replacement and re-solving. Computes per-cell-type percentile CI,
     * bootstrap p-value (H0: w_c = 0), and BH-adjusted q-value.
     *
     * Parallelizes over replicates if {@code bootstrapThreads > 1}. Each thread
     * gets a deterministic sub-seed derived from {@link #bootstrapSeed} so the
     * total resampling order is reproducible independent of completion order.
     */
    private BootstrapResult runBootstrap(double[][] refMatrix, double[] queryVector, double[] pointEstimate)
            throws InterruptedException {
        int M = refMatrix.length;
        int K = refMatrix[0].length;
        int B = nBootstrap;

        double[][] replicates = new double[B][K];

        // Pre-generate per-replicate resampling indices so parallel workers
        // consume a deterministic sequence regardless of completion order.
        long baseSeed = (bootstrapSeed >= 0) ? bootstrapSeed : System.nanoTime();
        Random idxRng = new Random(baseSeed);
        final int[][] bootIdx;

        // Decide uniform vs stratified. Stratified is active when the user
        // set -bootstrapStratified AND the reference panel populated a
        // usable `target` column (at least two distinct labels, enough
        // markers per group to bootstrap meaningfully).
        boolean useStratified = bootstrapStratified && canStratify(M);
        if (bootstrapStratified && !useStratified) {
            log.warn("  -bootstrapStratified requested but reference panel lacks usable "
                    + "`target` column or too few per-group markers; falling back to uniform.");
        }

        if (useStratified) {
            // Group marker indices by `target` label, then resample within each group.
            LinkedHashMap<String, List<Integer>> groups = new LinkedHashMap<>();
            for (int i = 0; i < M; i++) {
                String t = (i < markerTargets.size()) ? markerTargets.get(i) : null;
                if (t == null) t = "__unlabeled__";
                groups.computeIfAbsent(t, k -> new ArrayList<>()).add(i);
            }
            log.info("  stratified bootstrap: {} groups, group sizes: {}",
                    groups.size(),
                    groups.entrySet().stream()
                            .map(e -> e.getKey() + "=" + e.getValue().size())
                            .collect(Collectors.joining(", ")));

            bootIdx = new int[B][M];
            for (int b = 0; b < B; b++) {
                int writeOffset = 0;
                for (List<Integer> groupIndices : groups.values()) {
                    int g = groupIndices.size();
                    for (int k = 0; k < g; k++) {
                        bootIdx[b][writeOffset + k] = groupIndices.get(idxRng.nextInt(g));
                    }
                    writeOffset += g;
                }
            }
        } else {
            // Uniform bootstrap over all markers.
            bootIdx = new int[B][M];
            for (int b = 0; b < B; b++) {
                for (int i = 0; i < M; i++) {
                    bootIdx[b][i] = idxRng.nextInt(M);
                }
            }
        }

        Runnable logProgress = () -> {}; // no-op; keeps call sites simple
        int nThreads = Math.max(1, bootstrapThreads);

        if (nThreads == 1) {
            for (int b = 0; b < B; b++) {
                replicates[b] = runOneBootstrapReplicate(refMatrix, queryVector, bootIdx[b], K);
                if ((b + 1) % Math.max(1, B / 10) == 0) {
                    log.info("  bootstrap replicate {}/{}", b + 1, B);
                }
            }
        } else {
            java.util.concurrent.ExecutorService exec = java.util.concurrent.Executors.newFixedThreadPool(nThreads);
            java.util.List<java.util.concurrent.Future<?>> futures = new java.util.ArrayList<>(B);
            java.util.concurrent.atomic.AtomicInteger done = new java.util.concurrent.atomic.AtomicInteger(0);
            for (int b = 0; b < B; b++) {
                final int bb = b;
                futures.add(exec.submit(() -> {
                    replicates[bb] = runOneBootstrapReplicate(refMatrix, queryVector, bootIdx[bb], K);
                    int d = done.incrementAndGet();
                    if (d % Math.max(1, B / 10) == 0) {
                        log.info("  bootstrap replicate {}/{}", d, B);
                    }
                }));
            }
            for (java.util.concurrent.Future<?> f : futures) {
                try {
                    f.get();
                } catch (java.util.concurrent.ExecutionException ee) {
                    throw new RuntimeException("Bootstrap replicate failed", ee.getCause());
                }
            }
            exec.shutdown();
        }

        // Compute percentile CI
        double alpha = 1.0 - ciLevel;
        double loPct = alpha / 2.0;
        double hiPct = 1.0 - alpha / 2.0;
        double[] ciLower = new double[K];
        double[] ciUpper = new double[K];
        double[] column = new double[B];
        for (int c = 0; c < K; c++) {
            for (int b = 0; b < B; b++) column[b] = replicates[b][c];
            double[] sorted = column.clone();
            Arrays.sort(sorted);
            ciLower[c] = percentileSorted(sorted, loPct);
            ciUpper[c] = percentileSorted(sorted, hiPct);
        }

        // Bootstrap p-value: Pr(w_c <= epsilon | bootstrap).
        // Treat "essentially zero" as w_c <= 1e-6 to absorb tiny NNLS noise.
        double eps = 1e-6;
        double[] pValue = new double[K];
        for (int c = 0; c < K; c++) {
            int nZero = 0;
            for (int b = 0; b < B; b++) if (replicates[b][c] <= eps) nZero++;
            // Add-one smoothing so p is never exactly 0 (analogous to (k+1)/(B+1)).
            pValue[c] = (nZero + 1.0) / (B + 1.0);
        }

        double[] qValue = benjaminiHochberg(pValue);

        return new BootstrapResult(ciLower, ciUpper, pValue, qValue, replicates);
    }

    /**
     * True when stratified bootstrap can run: (a) markerTargets is populated
     * and aligns with M, (b) at least 2 distinct non-null labels, (c) no group
     * has fewer than 2 markers (single-marker groups give zero-variance
     * bootstrap samples, which trivially inflate CI width elsewhere).
     */
    private boolean canStratify(int M) {
        if (markerTargets == null || markerTargets.size() != M) return false;
        LinkedHashMap<String, Integer> counts = new LinkedHashMap<>();
        int labeled = 0;
        for (String t : markerTargets) {
            if (t == null || t.isEmpty()) continue;
            labeled++;
            counts.merge(t, 1, Integer::sum);
        }
        if (labeled < M) return false; // need every marker labeled to stratify cleanly
        if (counts.size() < 2) return false;
        for (int n : counts.values()) if (n < 2) return false;
        return true;
    }

    /** Per-sample permutation-test result, parallel in shape to BootstrapResult. */
    static class PermutationResult {
        final double[] pValue;   // length K, from column-permutation test
        final double[] qValue;   // length K, BH-adjusted
        final int nPermutations;

        PermutationResult(double[] pValue, double[] qValue, int nPermutations) {
            this.pValue = pValue;
            this.qValue = qValue;
            this.nPermutations = nPermutations;
        }
    }

    /**
     * Column-permutation test for each cell type.
     *
     * For each c in 0..K-1:
     *   1. Save the original column X[:, c].
     *   2. For b = 1..P:
     *      a. Shuffle the rows of X[:, c] into a new column X'[:, c].
     *      b. Solve NNLS on (X', y), giving w_permuted.
     *      c. Record w_permuted[c].
     *   3. Restore the original column.
     *   4. p_c = (#{b: w_permuted[c] >= w_observed[c]} + 1) / (P + 1)
     *
     * This tests whether the arrangement of the c-th reference column against
     * the sample's binarized vector is significantly better than a random
     * permutation of the same column values. Smaller p = stronger evidence
     * that the signal in column c is specific to the sample.
     *
     * Parallelizes across permutations within each cell type (the c loop
     * is sequential because it mutates the shared X column). Uses a seeded
     * RNG to pre-generate all permutation orders for reproducibility.
     */
    private PermutationResult runPermutationTest(double[][] refMatrix, double[] queryVector, double[] pointEstimate)
            throws InterruptedException {
        int M = refMatrix.length;
        int K = refMatrix[0].length;
        int P = nPermutations;

        long baseSeed = (permutationSeed >= 0) ? permutationSeed : System.nanoTime();
        Random permRng = new Random(baseSeed);

        // Pre-generate K * P permutations: permOrders[c][b] is a length-M
        // permutation of [0, M) that will re-order column c in replicate b.
        int[][][] permOrders = new int[K][P][];
        int[] identity = new int[M];
        for (int i = 0; i < M; i++) identity[i] = i;
        for (int c = 0; c < K; c++) {
            for (int b = 0; b < P; b++) {
                int[] order = identity.clone();
                // Fisher-Yates shuffle
                for (int i = M - 1; i > 0; i--) {
                    int j = permRng.nextInt(i + 1);
                    int tmp = order[i]; order[i] = order[j]; order[j] = tmp;
                }
                permOrders[c][b] = order;
            }
        }

        double[] pValue = new double[K];
        int nThreads = Math.max(1, bootstrapThreads);

        for (int c = 0; c < K; c++) {
            final int cc = c;
            final double observed = pointEstimate[c];
            double[] originalCol = new double[M];
            for (int i = 0; i < M; i++) originalCol[i] = refMatrix[i][cc];

            // Snapshot of the rest of the matrix is implicit: we only touch column cc.
            // Use atomic counter for thread-safe tallying.
            java.util.concurrent.atomic.AtomicInteger geCount = new java.util.concurrent.atomic.AtomicInteger(0);

            Runnable onePermutation = () -> {};  // overwritten below

            if (nThreads == 1) {
                double[] wPerm = new double[K];
                double[][] Xp = refMatrix;  // we mutate column cc in place then restore
                for (int b = 0; b < P; b++) {
                    int[] order = permOrders[cc][b];
                    // Install permuted column
                    double[] newCol = new double[M];
                    for (int i = 0; i < M; i++) newCol[i] = originalCol[order[i]];
                    for (int i = 0; i < M; i++) Xp[i][cc] = newCol[i];
                    wPerm = solveNNLS(Xp, queryVector);
                    if (wPerm[cc] >= observed) geCount.incrementAndGet();
                    if ((b + 1) % Math.max(1, P / 10) == 0) {
                        log.info("  permutation CT{}/{} replicate {}/{}", cc + 1, K, b + 1, P);
                    }
                }
                // Restore original column
                for (int i = 0; i < M; i++) Xp[i][cc] = originalCol[i];
            } else {
                // Parallel permutations: each thread gets its own deep-copied X
                // so column mutations don't race. Deep copy is O(M*K) per task
                // — acceptable because K is small and NNLS itself is O(M*K*iter).
                java.util.concurrent.ExecutorService exec = java.util.concurrent.Executors.newFixedThreadPool(nThreads);
                java.util.List<java.util.concurrent.Future<?>> futures = new java.util.ArrayList<>(P);
                java.util.concurrent.atomic.AtomicInteger done = new java.util.concurrent.atomic.AtomicInteger(0);
                for (int b = 0; b < P; b++) {
                    final int bb = b;
                    futures.add(exec.submit(() -> {
                        double[][] Xp = new double[M][K];
                        for (int i = 0; i < M; i++) {
                            System.arraycopy(refMatrix[i], 0, Xp[i], 0, K);
                        }
                        int[] order = permOrders[cc][bb];
                        for (int i = 0; i < M; i++) Xp[i][cc] = originalCol[order[i]];
                        double[] wPerm = solveNNLS(Xp, queryVector);
                        if (wPerm[cc] >= observed) geCount.incrementAndGet();
                        int d = done.incrementAndGet();
                        if (d % Math.max(1, P / 10) == 0) {
                            log.info("  permutation CT{}/{} replicate {}/{}", cc + 1, K, d, P);
                        }
                    }));
                }
                for (java.util.concurrent.Future<?> f : futures) {
                    try {
                        f.get();
                    } catch (java.util.concurrent.ExecutionException ee) {
                        exec.shutdown();
                        throw new RuntimeException("Permutation replicate failed for cell type "
                                + cellTypesForLog(cc), ee.getCause());
                    }
                }
                exec.shutdown();
            }

            pValue[cc] = (geCount.get() + 1.0) / (P + 1.0);
        }

        double[] qValue = benjaminiHochberg(pValue);
        return new PermutationResult(pValue, qValue, P);
    }

    /** Safe index-based cell-type label for error messages (avoids NPE when cellTypes is null). */
    private String cellTypesForLog(int c) {
        return "index " + c;
    }

    /** One NNLS replicate on a bootstrapped marker subsample. */
    private double[] runOneBootstrapReplicate(double[][] refMatrix, double[] queryVector, int[] idx, int K) {
        int M = idx.length;
        double[][] Xb = new double[M][K];
        double[] Yb = new double[M];
        for (int i = 0; i < M; i++) {
            int r = idx[i];
            Yb[i] = queryVector[r];
            // System.arraycopy avoids per-element copy overhead
            System.arraycopy(refMatrix[r], 0, Xb[i], 0, K);
        }
        // Use NNLS (same as the point estimate) regardless of the -solver option:
        // QP with equality-constraints adds no stochastic structure, and NNLS
        // matches what most deconvolution papers use for bootstrap.
        return solveNNLS(Xb, Yb);
    }

    /** Linear-interpolation percentile on a pre-sorted array. {@code q} is in [0, 1]. */
    private static double percentileSorted(double[] sorted, double q) {
        if (sorted.length == 0) return Double.NaN;
        if (sorted.length == 1) return sorted[0];
        double idx = q * (sorted.length - 1);
        int lo = (int) Math.floor(idx);
        int hi = (int) Math.ceil(idx);
        if (lo == hi) return sorted[lo];
        double frac = idx - lo;
        return sorted[lo] * (1.0 - frac) + sorted[hi] * frac;
    }

    /**
     * Benjamini-Hochberg FDR adjustment: for sorted p-values p_(1) <= ... <= p_(K),
     * q_(i) = min_{j >= i} p_(j) * K / j, then map back to the original order.
     */
    private static double[] benjaminiHochberg(double[] pvals) {
        int K = pvals.length;
        Integer[] order = new Integer[K];
        for (int i = 0; i < K; i++) order[i] = i;
        Arrays.sort(order, Comparator.comparingDouble(i -> pvals[i]));
        double[] qSorted = new double[K];
        double minSoFar = 1.0;
        for (int r = K - 1; r >= 0; r--) {
            double raw = pvals[order[r]] * (double) K / (double) (r + 1);
            if (raw < minSoFar) minSoFar = raw;
            qSorted[r] = Math.min(minSoFar, 1.0);
        }
        double[] q = new double[K];
        for (int r = 0; r < K; r++) q[order[r]] = qSorted[r];
        return q;
    }

    /**
     * Solve NNLS: minimize ||Y - X*w||^2 subject to w >= 0, then normalize sum(w)=1.
     */
    private double[] solveNNLS(double[][] refMatrix, double[] queryVector) {
        // Handle the case where we're called as fallback with null args
        if (refMatrix == null || queryVector == null) {
            return new double[0];
        }

        int n = refMatrix[0].length;
        int m = refMatrix.length;

        // Remove rows where query is NaN
        List<Integer> validRows = new ArrayList<>();
        for (int i = 0; i < m; i++) {
            if (!Double.isNaN(queryVector[i])) validRows.add(i);
        }
        if (validRows.isEmpty()) {
            double[] zero = new double[n];
            Arrays.fill(zero, 1.0 / n);
            return zero;
        }

        RealMatrix X = new Array2DRowRealMatrix(validRows.size(), n);
        RealVector Y = new ArrayRealVector(validRows.size());
        for (int i = 0; i < validRows.size(); i++) {
            int row = validRows.get(i);
            Y.setEntry(i, queryVector[row]);
            for (int j = 0; j < n; j++) {
                X.setEntry(i, j, refMatrix[row][j]);
            }
        }

        // Lawson-Hanson NNLS algorithm
        double[] w = lawsonHansonNNLS(X, Y);

        // Normalize to sum = 1
        double sum = 0;
        for (double v : w) sum += v;
        if (sum > 0) {
            for (int i = 0; i < w.length; i++) w[i] /= sum;
        } else {
            Arrays.fill(w, 1.0 / n);
        }
        return w;
    }

    /**
     * Lawson-Hanson NNLS algorithm.
     * Minimize ||A*x - b||^2 subject to x >= 0.
     */
    private double[] lawsonHansonNNLS(RealMatrix A, RealVector b) {
        int m = A.getRowDimension();
        int n = A.getColumnDimension();
        double[] x = new double[n];
        boolean[] passive = new boolean[n]; // passive set (unconstrained)
        int maxIter = 3 * n;

        RealMatrix AtA = A.transpose().multiply(A);
        RealVector Atb = A.transpose().operate(b);

        for (int iter = 0; iter < maxIter; iter++) {
            // Compute gradient: w = A^T(b - Ax)
            RealVector xVec = new ArrayRealVector(x);
            RealVector gradient = Atb.subtract(AtA.operate(xVec));

            // Find the maximum gradient among zero (active) variables
            int maxIdx = -1;
            double maxGrad = 0;
            for (int i = 0; i < n; i++) {
                if (!passive[i] && gradient.getEntry(i) > maxGrad) {
                    maxGrad = gradient.getEntry(i);
                    maxIdx = i;
                }
            }

            if (maxIdx < 0 || maxGrad <= 1e-10) break; // converged

            passive[maxIdx] = true;

            // Inner loop: solve unconstrained LS for passive set
            while (true) {
                List<Integer> passiveIndices = new ArrayList<>();
                for (int i = 0; i < n; i++) if (passive[i]) passiveIndices.add(i);

                // Extract passive columns
                RealMatrix Ap = new Array2DRowRealMatrix(m, passiveIndices.size());
                for (int j = 0; j < passiveIndices.size(); j++) {
                    Ap.setColumn(j, A.getColumn(passiveIndices.get(j)));
                }

                // Solve least squares for passive variables
                RealVector sp;
                try {
                    DecompositionSolver solver = new QRDecomposition(Ap).getSolver();
                    sp = solver.solve(b);
                } catch (Exception e) {
                    break;
                }

                // Check for negative values in passive set
                double minVal = Double.MAX_VALUE;
                int minPassiveIdx = -1;
                for (int j = 0; j < passiveIndices.size(); j++) {
                    if (sp.getEntry(j) < minVal) {
                        minVal = sp.getEntry(j);
                        minPassiveIdx = j;
                    }
                }

                if (minVal > 0) {
                    // All positive — accept solution
                    for (int j = 0; j < passiveIndices.size(); j++) {
                        x[passiveIndices.get(j)] = sp.getEntry(j);
                    }
                    break;
                }

                // Interpolate toward feasibility
                double alpha = Double.MAX_VALUE;
                int alphaIdx = -1;
                for (int j = 0; j < passiveIndices.size(); j++) {
                    int pi = passiveIndices.get(j);
                    if (sp.getEntry(j) <= 0) {
                        double ratio = x[pi] / (x[pi] - sp.getEntry(j));
                        if (ratio < alpha) {
                            alpha = ratio;
                            alphaIdx = pi;
                        }
                    }
                }

                // Update x
                for (int j = 0; j < passiveIndices.size(); j++) {
                    int pi = passiveIndices.get(j);
                    x[pi] += alpha * (sp.getEntry(j) - x[pi]);
                }

                // Move variables that hit zero back to active set
                for (int j = 0; j < passiveIndices.size(); j++) {
                    int pi = passiveIndices.get(j);
                    if (Math.abs(x[pi]) < 1e-10) {
                        x[pi] = 0;
                        passive[pi] = false;
                    }
                }
            }
        }

        return x;
    }
